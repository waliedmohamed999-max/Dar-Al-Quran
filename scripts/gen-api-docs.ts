// Regenerates docs/API.md from the endpoint table, so documentation cannot drift from routes.
import "dotenv/config";
import { writeFileSync } from "node:fs";
import { endpoints } from "../src/modules/api/endpoints";

const rows = endpoints.map((e) => `| ${e.method} | \`/api/v1${e.path}\` | ${e.public ? "public" : e.perm ?? "signed in"} | ${e.limit ? `${e.limit.max}/${e.limit.windowSec}s` : "120/60s"} | ${e.summary} |`);
writeFileSync("docs/API.md", `# API (/api/v1)\n\nGenerated by \`npm run docs:api\`. Responses are \`{ "data": ... }\` or \`{ "error": code }\`. State-changing requests must come from the same origin. Row level security applies in addition to the listed permission.\n\n| Method | Path | Access | Rate limit | Purpose |\n|---|---|---|---|---|\n${rows.join("\n")}\n`);
console.log(`${endpoints.length} endpoints`);
